-- Original build selection remains immutable even when later eligibility changes.
CREATE TABLE app.portfolio_build_tasks (
 run_id app.identity PRIMARY KEY REFERENCES app.runs,
 mandate_id app.identity NOT NULL REFERENCES app.portfolio_mandates,
 snapshot_id app.identity NOT NULL REFERENCES app.forward_weight_snapshots,
 request app.document NOT NULL
);
CREATE TRIGGER immutable BEFORE UPDATE OR DELETE ON app.portfolio_build_tasks
 FOR EACH ROW EXECUTE FUNCTION app.reject_change();

