export function reasonText(value?: string | null, fallback = '原因尚未分类，请展开原始原因并按原始身份核对。'): string { return value ? reasons[value] ?? fallback : fallback; }
export function Reason({ value, fallback }: { value?: string | null; fallback?: string }) {
  return <div className="record-reason"><p>{reasonText(value, fallback)}</p>{value && <details className="reason-technical"><summary>原始原因</summary><code>{value}</code></details>}</div>;
}
export function ExecutionFailure({ error, detail, identity, title = '计算未完成' }: { error?: string | null; detail?: ExecutionErrorDetail | null; identity?: string; title?: string }) {
  if (!error && !detail) return null;
  return <div className="recorded-error" role="alert"><strong>{title}</strong>{detail ? <><p>{detail.message}</p><p className="failure-action"><span>处理建议</span>{detail.action}</p><details><summary>技术详情</summary><code>{detail.code}</code>{error && error !== detail.code && <code>{error}</code>}<span>类别：{({ model: '模型', data: '数据', request: '输入', resource: '资源', runtime: '运行时', cancelled: '取消', unknown: '未知' })[detail.category]}</span>{detail.operation && <code>操作：{detail.operation}</code>}{detail.stage && <span>阶段：{({ compile: '编译', execute: '执行', decode: '读取输出', validate: '验证输出' })[detail.stage]}</span>}</details></> : <Reason value={error} fallback="执行失败，当前记录未提供已分类诊断。请按原始任务身份核对，不要用新身份重复执行。" />}{identity && <p className="failure-identity">{identity}</p>}</div>;
}
