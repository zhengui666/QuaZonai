//! Runtime-owned immutable native catalog metadata, never client assertions of evidence.
use crate::{
    research::{DataOrigin, DataPartition, PitStatus},
    runtime::RuntimeDataKind,
    DbCounter, SchemaV1,
};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

/// Frozen alongside the native catalog, independently of a simulation request.
pub const MAKER_TAKER_FEES_FILE: &str = "frozen-maker-taker-fees.json";

/// Original venue fee policy. Native instruments contain contract terms, not fee rates.
/// Freezing this record preserves its source identity; it does not certify the
/// historical availability or applicability of an otherwise unverified source.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct FrozenMakerTakerFeesV1 {
    pub schema_version: SchemaV1,
    #[schema(min_length = 1, max_length = 2000)]
    pub source_reference: String,
    #[schema(min_length = 1, max_length = 120)]
    pub source_version: String,
    /// Fee-source origin is independent of the underlying market-data origin.
    pub origin: DataOrigin,
    #[schema(min_length = 1, max_length = 120)]
    pub venue: String,
    #[schema(min_length = 1, max_length = 40)]
    pub currency: String,
    pub currency_precision: u8,
    pub available_at_ns: DbCounter,
    /// One unchanged policy over [valid_from_ns, valid_until_ns).
    pub valid_from_ns: DbCounter,
    pub valid_until_ns: DbCounter,
    #[schema(min_items = 1, max_items = 65536)]
    pub rates: Vec<crate::science::NativeFeeRateV1>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum DataRevisionPolicy {
    AsKnownThen,
    Restated,
    Unknown,
}

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct NativeUniverseMemberV1 {
    #[schema(min_length = 1, max_length = 200)]
    pub instrument_id: String,
    pub valid_from: DateTime<Utc>,
    pub valid_until: Option<DateTime<Utc>>,
    pub available_at: DateTime<Utc>,
    /// None means unknown classification; Some([]) is explicitly ungrouped.
    pub groups: Option<Vec<String>>,
}

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct NativeUniverseV1 {
    #[schema(min_length = 1, max_length = 120)]
    pub name: String,
    #[schema(min_length = 1, max_length = 120)]
    pub calendar_ref: String,
    #[schema(min_length = 1, max_length = 120)]
    pub calendar_version: String,
    pub calendar_sessions: Option<crate::science::NativeCalendarSessionsV1>,
    pub selection_asof: DateTime<Utc>,
    pub has_historical_membership: bool,
    pub coverage_start: DateTime<Utc>,
    pub coverage_end: DateTime<Utc>,
    #[schema(min_items = 1)]
    pub membership: Vec<NativeUniverseMemberV1>,
    /// Original Rust InstrumentAny externally tagged Serde definitions, e.g. {"CurrencyPair":{...}}.
    /// This document is metadata, not a second instrument or matching engine.
    #[schema(min_items = 1)]
    pub instrument_definitions: Vec<serde_json::Value>,
}

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct RuntimeCatalogMetadataV1 {
    pub schema_version: SchemaV1,
    #[schema(min_length = 1, max_length = 512)]
    pub registered_ref: String,
    #[schema(min_length = 1, max_length = 512)]
    pub native_snapshot_ref: String,
    #[schema(min_length = 1, max_length = 120)]
    pub storage_version: String,
    #[schema(min_length = 1, max_length = 120)]
    pub provider_kind: String,
    pub data_kind: RuntimeDataKind,
    pub partition: DataPartition,
    pub event_start: DateTime<Utc>,
    pub event_end: DateTime<Utc>,
    pub available_through: DateTime<Utc>,
    pub row_count: DbCounter,
    pub origin: DataOrigin,
    pub pit_status: PitStatus,
    pub revision_policy: DataRevisionPolicy,
    #[schema(min_length = 1, max_length = 2000)]
    pub provenance_reference: String,
    /// A recorded source explanation. Never inferred merely from ts_init <= cutoff.
    #[schema(min_length = 1, max_length = 8000)]
    pub availability_provenance: String,
    pub universe: NativeUniverseV1,
    /// Exact original quality report generated by the native source owner.
    /// Fresh DATA_VALIDATE still reopens the registered snapshot before consumption.
    pub quality: crate::execution::NativeDataQualityReportV1,
    /// Exact catalog-owned source file. None permits data-only use, never an
    /// implicit zero fee or a simulation-settings declaration of source evidence.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub execution_fees: Option<FrozenMakerTakerFeesV1>,
    /// Original source attachment descriptors. The registered Dataset and native
    /// metadata artifact preserve the source association without extending license scope.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub recorded_feature_inputs: Option<RecordedFeatureInputsV1>,
}

#[derive(Clone, Debug, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct CatalogVersionQuery {
    #[schema(min_length = 1, max_length = 120)]
    pub storage_version: String,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct RecordedFeatureFragmentV1 {
    /// Stable attachment key, never a filesystem path.
    #[schema(
        min_length = 1,
        max_length = 120,
        pattern = r"^[A-Za-z0-9][A-Za-z0-9._-]{0,119}(?![\s\S])"
    )]
    pub part_key: String,
    #[schema(schema_with = recorded_feature_bytes_schema)]
    pub byte_count: DbCounter,
    #[schema(schema_with = recorded_feature_observations_schema)]
    pub observations: DbCounter,
    pub min_event_ns: DbCounter,
    pub max_event_ns: DbCounter,
    pub min_observed_available_ns: DbCounter,
    pub max_observed_available_ns: DbCounter,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
pub struct RecordedFeatureInputsV1 {
    pub schema_version: SchemaV1,
    /// Original source event selection [start, end), independent of BAR closes.
    pub source_selection_start_ns: DbCounter,
    pub source_selection_end_ns: DbCounter,
    pub partition: DataPartition,
    /// All original observations are retained across the declared parts.
    #[schema(min_items = 1)]
    pub fragments: Vec<RecordedFeatureFragmentV1>,
}

pub(crate) fn recorded_feature_bytes_schema(
) -> utoipa::openapi::RefOr<utoipa::openapi::schema::Schema> {
    crate::scalars::positive_db_counter_schema()
}

fn recorded_feature_observations_schema() -> utoipa::openapi::RefOr<utoipa::openapi::schema::Schema>
{
    crate::scalars::positive_db_counter_schema()
}
